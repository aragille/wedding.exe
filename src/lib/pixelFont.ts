export const GLYPH_HEIGHT = 7

export interface LaidOutGlyph {
  char: string
  /** x offset in cells */
  x: number
  width: number
  cells: Array<[number, number]>
}

/** Lay out a string into glyph cell lists (1-cell tracking). Unknown chars become spaces. */
export function layoutText(text: string, tracking = 1): { glyphs: LaidOutGlyph[]; width: number } {
  let x = 0
  const glyphs: LaidOutGlyph[] = []
  for (const raw of text.toUpperCase()) {
    const rows = GLYPHS[raw] ?? GLYPHS[' ']
    const width = rows[0].length
    const cells: Array<[number, number]> = []
    rows.forEach((row, y) => {
      for (let cx = 0; cx < row.length; cx++) if (row[cx] === '#') cells.push([cx, y])
    })
    glyphs.push({ char: raw, x, width, cells })
    x += width + tracking
  }
  return { glyphs, width: Math.max(0, x - tracking) }
}

/** Build a single SVG path from a list of cells (each cell = `unit` × `unit`). */
export function cellsToPath(cells: Array<[number, number]>, unit: number, ox = 0, oy = 0) {
  let d = ''
  for (const [cx, cy] of cells) d += `M${ox + cx * unit} ${oy + cy * unit}h${unit}v${unit}h${-unit}z`
  return d
}
